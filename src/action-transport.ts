import type { Navigation, SubmitFunction, SubmitOptions } from 'react-router';

/** Body representations available on native navigation and fetcher state for pending inspection. */
export type ActionSubmission = Pick<Navigation, 'json' | 'formData' | 'text'>;

/** Decoded intent and handler input, independent of the chosen wire format. */
export type ActionPayload = {
  /** Non-empty key identifying a handler in the route definitions. */
  intent: string;
  /** Value passed to the handler; validate application-specific input in the handler. */
  body: unknown;
  /**
   * Opaque identifier generated by the hook. Preserve it across encode/decode/inspect
   * so pending navigation can be attributed to the hook that submitted it.
   */
  submissionId?: string;
};

/**
 * Customize how intents and bodies cross React Router's submission boundary.
 * Implement all three methods using the same protocol so execution and pending
 * inspection agree. The transport does not replace business-input validation.
 */
export interface ActionTransport {
  /**
   * Create a native submit target for the selected encoding without mutating payload.body.
   * Runs before router submission; an exception rejects the submit callback's promise.
   */
  encode(
    payload: ActionPayload,
    encType: NonNullable<SubmitOptions['encType']>
  ): Parameters<SubmitFunction>[0];
  /**
   * Read a request into a payload. The route action passes a clone, so this method
   * may consume its body. Return undefined for requests outside this protocol to
   * allow fallback handling; throw ActionRequestError for malformed protocol input.
   * Other exceptions propagate to React Router unchanged.
   */
  decode(request: Request): Promise<ActionPayload | undefined>;
  /**
   * Identify an intent and submissionId from native pending state without mutation.
   * Called during render: remain synchronous and return undefined for unrecognized
   * or malformed input rather than throwing and interrupting rendering.
   */
  inspect(submission: ActionSubmission): Pick<ActionPayload, 'intent' | 'submissionId'> | undefined;
}

/**
 * Marks a malformed intent request. Errors thrown by decode are translated through
 * invalidRequest (an empty 400 Response by default); errors thrown by encode reject
 * the caller's submission promise. Use the code for application-specific messages.
 */
export class ActionRequestError extends Error {
  constructor(readonly code: 'invalid-request' | 'unknown-intent' = 'invalid-request') {
    super(code);
    this.name = 'ActionRequestError';
  }
}

const intentField = '__action_intent';
const submissionField = '__action_submission';
const envelopeFields = new Set(['intent', 'body', 'submissionId']);

const invalidRequest = (): never => {
  throw new ActionRequestError();
};

const identifier = (value: unknown): string =>
  typeof value === 'string' && value.length > 0 ? value : invalidRequest();

const readEnvelope = (value: unknown): ActionPayload => {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return invalidRequest();
  if (!Object.hasOwn(value, 'intent')) return invalidRequest();
  if (Object.keys(value).some((key) => !envelopeFields.has(key))) return invalidRequest();
  const intent = identifier('intent' in value ? value.intent : undefined);
  const submissionId = 'submissionId' in value ? identifier(value.submissionId) : undefined;
  return {
    intent,
    body: 'body' in value ? value.body : undefined,
    ...(submissionId === undefined ? {} : { submissionId }),
  };
};

// Snapshot plain JSON data before stringify can invoke getters/toJSON or coerce
// unsupported values. Only undefined object properties may be silently omitted.
const jsonSnapshot = (value: unknown, ancestors = new Set<object>()): unknown => {
  if (value === null || typeof value === 'string' || typeof value === 'boolean') return value;
  if (typeof value === 'number') return Number.isFinite(value) ? value : invalidRequest();
  if (typeof value !== 'object' || ancestors.has(value)) return invalidRequest();
  const array = Array.isArray(value);
  const prototype: unknown = Object.getPrototypeOf(value);
  if (!array && prototype !== Object.prototype && prototype !== null) return invalidRequest();
  ancestors.add(value);
  try {
    const entries = Reflect.ownKeys(value).flatMap((key): [string, unknown][] => {
      if (array && key === 'length') return [];
      const descriptor = Object.getOwnPropertyDescriptor(value, key);
      if (typeof key !== 'string' || !descriptor?.enumerable || !('value' in descriptor)) {
        return invalidRequest();
      }
      if (!array && descriptor.value === undefined) return [];
      return [[key, jsonSnapshot(descriptor.value, ancestors)]];
    });
    if (!array) return Object.fromEntries(entries);
    if (entries.length !== value.length || entries.some(([key], index) => key !== String(index))) {
      return invalidRequest();
    }
    return entries.map(([, item]) => item);
  } finally {
    // Track the current path only: a shared reference in another branch is not a cycle.
    ancestors.delete(value);
  }
};

const readForm = (form: FormData): ActionPayload | undefined => {
  const intents = form.getAll(intentField);
  const submissions = form.getAll(submissionField);
  if (intents.length === 0 && submissions.length === 0) return undefined;
  if (intents.length !== 1 || submissions.length > 1) return invalidRequest();
  const intent = identifier(intents[0]);
  const submissionId = submissions.length === 1 ? identifier(submissions[0]) : undefined;
  const body = new FormData();
  for (const [key, value] of form) {
    if (key !== intentField && key !== submissionField) body.append(key, value);
  }
  return { intent, body, ...(submissionId === undefined ? {} : { submissionId }) };
};

/**
 * Built-in transport for JSON, text, multipart, and URL-encoded submissions.
 *
 * JSON and text/plain carry { intent, body?, submissionId? }; text/plain is a JSON
 * envelope, not an arbitrary text protocol. Missing bodies remain undefined.
 * Undefined object properties are omitted; values that cannot round-trip as plain
 * JSON (including Date, File, cycles, and undefined array entries) are rejected.
 *
 * Form encodings require FormData, or undefined for an empty form. They reserve
 * __action_intent and __action_submission; handlers receive a copy without those
 * fields. Repeated fields are preserved, and files require multipart/form-data.
 *
 * Decoding returns undefined for unsupported content types or forms without
 * protocol fields. Invalid JSON/text envelopes and malformed form metadata throw
 * ActionRequestError. Business-input validation remains the handler's responsibility.
 */
export const defaultActionTransport: ActionTransport = {
  encode(payload, encType) {
    const intent = identifier(payload.intent);
    const submissionId =
      payload.submissionId === undefined ? undefined : identifier(payload.submissionId);
    if (encType === 'application/json' || encType === 'text/plain') {
      return JSON.stringify({
        intent,
        ...(payload.body === undefined ? {} : { body: jsonSnapshot(payload.body) }),
        ...(submissionId === undefined ? {} : { submissionId }),
      });
    }
    const body = payload.body === undefined ? new FormData() : payload.body;
    if (!(body instanceof FormData)) return invalidRequest();
    const form = new FormData();
    for (const [key, value] of body) {
      if (key === intentField || key === submissionField) return invalidRequest();
      if (encType === 'application/x-www-form-urlencoded' && typeof value !== 'string') {
        return invalidRequest();
      }
      form.append(key, value);
    }
    form.append(intentField, intent);
    if (submissionId !== undefined) form.append(submissionField, submissionId);
    return form;
  },
  async decode(request) {
    const contentType = request.headers.get('content-type')?.split(';')[0]?.trim().toLowerCase();
    if (contentType === 'application/json' || contentType === 'text/plain') {
      let value: unknown;
      try {
        value = await request.json();
      } catch (error) {
        if (request.signal.aborted) throw error;
        return invalidRequest();
      }
      return readEnvelope(value);
    }
    if (
      contentType === 'multipart/form-data' ||
      contentType === 'application/x-www-form-urlencoded'
    ) {
      let form: FormData;
      try {
        form = await request.formData();
      } catch (error) {
        if (request.signal.aborted) throw error;
        return invalidRequest();
      }
      return readForm(form);
    }
    return undefined;
  },
  inspect(submission) {
    try {
      const payload = submission.formData
        ? readForm(submission.formData)
        : readEnvelope(
            submission.json ??
              (submission.text === undefined ? undefined : JSON.parse(submission.text))
          );
      if (!payload) return undefined;
      const { intent, submissionId } = payload;
      return { intent, ...(submissionId === undefined ? {} : { submissionId }) };
    } catch {
      return undefined;
    }
  },
};
